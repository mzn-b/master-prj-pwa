/**
 * Whether this bundle is the survey build used with study participants.
 *
 * Participants compare the two implementations without being told which is the
 * web one (thesis §6.5.3), so a survey build hides every control that would
 * tell them: the "Inferenz im Web Worker" toggle, which only the web app has and
 * whose label names the web, and the two HUD toggles, whose readouts differ
 * between the apps (memory, CPU and thermal state are blank in a browser).
 *
 * Set by `npm run build:survey` (`vite build --mode survey`, which reads
 * `.env.survey`). A normal `npm run build` is the full production build. The
 * native app has the same switch, generated by its `scripts/stamp-build.mjs`.
 */
export const SURVEY_BUILD: boolean = import.meta.env.VITE_SURVEY_BUILD === "true";
